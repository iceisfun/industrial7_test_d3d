/* Texture2D creation validity matrix: one TEST per descriptor, all expectations are API-contract results
 * (E_INVALIDARG for illegal combinations, S_OK for legal ones, S_FALSE for validate-only calls). */
#include "txh.h"

#define OKAY S_OK
#define BAD E_INVALIDARG

static void tx_c2d(tx_ctx *c, const char *file, int line, UINT w, UINT h, UINT mips, UINT arr, DXGI_FORMAT f, D3D11_USAGE u,
                   UINT bind, UINT cpu, UINT misc, UINT sc, UINT sq, HRESULT want, UINT minfl) {
    D3D11_TEXTURE2D_DESC d, g; tx_init in; D3D11_SUBRESOURCE_DATA *sd = NULL; ID3D11Texture2D *t = NULL; HRESULT hr, hr2;
    int hard = c->fl >= (D3D_FEATURE_LEVEL)minfl;
    want = tx_resolve(c, want);
    memset(&in, 0, sizeof in);
    memset(&d, 0, sizeof d);
    d.Width = w; d.Height = h; d.MipLevels = mips; d.ArraySize = arr; d.Format = f; d.SampleDesc.Count = sc; d.SampleDesc.Quality = sq;
    d.Usage = u; d.BindFlags = bind; d.CPUAccessFlags = cpu; d.MiscFlags = misc;
    if (u == D3D11_USAGE_IMMUTABLE && w && h && arr && w <= 4096 && h <= 4096 && arr <= 64 && tx_init_make(&in, w, h, 1, mips <= 16 ? mips : 1, arr, f, 0, 0, 1)) sd = in.sd;
    hr = ID3D11Device_CreateTexture2D(c->dev, &d, sd, &t);
    t_check(!hard || hr == want, file, line, "CreateTexture2D", "got %s want %s (feature level %#x)", d3dh_hr_name(hr), d3dh_hr_name(want), c->fl);
    if (!hard && hr != want) t_note("%s:%d below feature level %#x: got %s want %s", file, line, minfl, d3dh_hr_name(hr), d3dh_hr_name(want));
    if (SUCCEEDED(hr) && t) {
        UINT em = mips ? mips : tx_full_mips(w > h ? w : h);
        ID3D11Texture2D_GetDesc(t, &g);
        t_check(g.Width == w && g.Height == h, file, line, "GetDesc size", "got %ux%u want %ux%u", g.Width, g.Height, w, h);
        t_check(g.MipLevels == em, file, line, "GetDesc mips", "got %u want %u", g.MipLevels, em);
        t_check(g.ArraySize == arr && g.Format == f, file, line, "GetDesc array/format", "got %u/%u want %u/%u", g.ArraySize, g.Format, arr, f);
        t_check(g.SampleDesc.Count == sc && g.SampleDesc.Quality == sq, file, line, "GetDesc sample", "got %u/%u", g.SampleDesc.Count, g.SampleDesc.Quality);
        t_check(g.Usage == u && g.BindFlags == bind && g.CPUAccessFlags == cpu && g.MiscFlags == misc, file, line, "GetDesc flags",
                "usage %u/%u bind %#x/%#x cpu %#x/%#x misc %#x/%#x", g.Usage, u, g.BindFlags, bind, g.CPUAccessFlags, cpu, g.MiscFlags, misc);
        ID3D11Texture2D_Release(t);
    }
    /* validate-only call: S_FALSE when the description is acceptable */
    hr2 = ID3D11Device_CreateTexture2D(c->dev, &d, sd, NULL);
    {
        HRESULT w2 = want == S_OK ? S_FALSE : want;
        t_check(!hard || hr2 == w2, file, line, "CreateTexture2D(validate only)", "got %s want %s", d3dh_hr_name(hr2), d3dh_hr_name(w2));
    }
    tx_init_free(&in);
}

#define C2D(nm, W, H, M, A, F, U, B, CP, MI, SC, SQ, WANT, MINFL) \
    DEVTEST(d3d11_textures_c2d_##nm) { tx_c2d(c, __FILE__, __LINE__, W, H, M, A, F, U, B, CP, MI, SC, SQ, WANT, MINFL); }

