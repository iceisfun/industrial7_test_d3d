#!/usr/bin/env python3
"""Regenerates shtable.h and assets/shaders/d3d11sh_*.hlsl from shaders.src."""
import os
here = os.path.dirname(os.path.abspath(__file__))
assets = os.path.join(here, "..", "..", "assets", "shaders")
ents = []
cur = None
for ln in open(os.path.join(here, "shaders.src")).read().splitlines():
    if ln.startswith("###"):
        n, t, fl = ln[3:].split()
        cur = [n, t, fl, []]; ents.append(cur)
    else:
        cur[3].append(ln)
FL = {"9_1": "0x9100", "10_0": "0xa000", "10_1": "0xa100", "11_0": "0xb000"}
out = ["/* GENERATED by gen_shtable.py from shaders.src */\n",
       "typedef struct { const char *name, *target, *src; unsigned minfl; } sh_ent;\n",
       "static const sh_ent sh_table[] = {\n"]
for n, t, fl, body in ents:
    src = "\n".join(body) + "\n"
    lines = src.split("\n")[:-1]
    lit = "\n".join('        "%s\\n"' % l.replace("\\", "\\\\").replace('"', '\\"') for l in lines)
    out.append('  { "%s", "%s",\n%s, %s },\n' % (n, t, lit, FL[fl]))
    with open(os.path.join(assets, "d3d11sh_%s.hlsl" % n), "w", newline="\n") as f:
        f.write("// d3d11_shaders corpus: target %s, entry main\n" % t + src)
out.append("};\n#define SH_NTABLE ((int)(sizeof(sh_table) / sizeof(sh_table[0])))\n")
open(os.path.join(here, "shtable.h"), "w").write("".join(out))
