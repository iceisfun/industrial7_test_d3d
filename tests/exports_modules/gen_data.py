#!/usr/bin/env python3
# Regenerates exports_data.c from tools/*_exports.json and a module metadata json (fetched from the reference index).
import json, sys, os
root = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..')
meta = json.load(open(sys.argv[1]))
mods = "d3d11 d3d9 d3d10 d3d10_1 d3d10core d3d10_1core d3d10warp d3d10level9 d3d11on12 d3d12 d3d12core d3d9on12 dxgi dxcore d3dcompiler_47 d3dscache d3d8thk ddraw dxilconv dxva2".split()
o = ['/* generated by gen_data.py - do not edit */', '#include "xm.h"', '']
for m in mods:
    ex = json.load(open(os.path.join(root, 'tools', m + '_exports.json')))
    o.append('static const xexp e_%s[] = {' % m)
    for e in sorted(ex, key=lambda e: e['ordinal']):
        n = '"%s"' % e['name'] if e['name'] else 'NULL'
        f = '"%s"' % e['forwarder'] if e['forwarder'] else 'NULL'
        o.append('  { %s, %d, 0x%x, %s },' % (n, e['ordinal'], e['rva'], f))
    o.append('};')
o.append('const xmod g_xm[XM_COUNT] = {')
for m in mods:
    mt = meta[m]
    o.append('  { "%s.dll", e_%s, (int)(sizeof e_%s / sizeof e_%s[0]), %d, "%s", "%s", "%s" },' % (
        m, m, m, m, mt['sub'], ','.join(mt['sec']), ','.join(d for d in mt['deps']), mt['ver']))
o.append('};')
open(os.path.join(os.path.dirname(os.path.abspath(__file__)), 'exports_data.c'), 'w').write('\n'.join(o) + '\n')
